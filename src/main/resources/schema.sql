CREATE TABLE listing (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_email varchar(255) NOT NULL,
    -- ADR-012 marketplace slice: the seller's Clerk subject; nullable until a legacy
    -- address-only row is claimed by its owner (identity-backfill.md rule 5).
    seller_subject varchar(255),
    title        varchar(255) NOT NULL,
    description  varchar(4000),
    category     varchar(255) NOT NULL,
    listing_type varchar(255) NOT NULL,
    status       varchar(255) NOT NULL,
    price        numeric(38, 2),
    course_code  varchar(255),
    school_id    bigint REFERENCES university (id) ON DELETE SET NULL,
    created_at   timestamp(6) with time zone NOT NULL,
    updated_at   timestamp(6) with time zone NOT NULL,
    CONSTRAINT listing_category_check CHECK (category IN
        ('BOOKS', 'CLOTHES', 'EVENT_TICKETS', 'FURNITURE', 'ELECTRONICS', 'OTHER')),
    CONSTRAINT listing_listing_type_check CHECK (listing_type IN
        ('SELL', 'RENT', 'FREE', 'LOOKING_FOR')),
    CONSTRAINT listing_status_check CHECK (status IN ('AVAILABLE', 'PENDING', 'SOLD'))
);

CREATE INDEX idx_listing_seller ON listing (seller_email);
CREATE INDEX idx_listing_seller_subject ON listing (seller_subject);
CREATE INDEX idx_listing_school ON listing (school_id);
CREATE INDEX idx_listing_status_category ON listing (status, category);
CREATE INDEX idx_listing_course_code ON listing (course_code);


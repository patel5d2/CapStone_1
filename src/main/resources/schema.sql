-- CampusBridge schema: every table, in one file.
--
-- Runs against the H2 in-memory database (PostgreSQL compatibility mode) on every
-- startup via spring.sql.init; the database starts empty each time, so this file is
-- the whole schema, not a migration. data.sql runs after it with the mock data.
-- Hibernate still validates the @Entity classes against these tables
-- (ddl-auto: validate), so change an entity and you must change this file too.
--
-- Built from the former Flyway migrations V1, V4, V5, V6 and V7, in that order.

-- ===========================================================================
-- V1 baseline
-- ===========================================================================

-- Ordering: parents before children, so the foreign keys below resolve.

-- ---------------------------------------------------------------------------
-- Directory (plain JDBC, not JPA — Hibernate never sees these three)
-- ---------------------------------------------------------------------------

CREATE TABLE university (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE
);

-- Column widths are deliberately generous. The previous H2 schema used
-- varchar(20) for names and varchar(40) for the city, which turned an ordinary
-- long surname into a 500 rather than a validation message.
CREATE TABLE student (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name        varchar(100) NOT NULL,
    last_name         varchar(100) NOT NULL,
    resident_city     varchar(100) NOT NULL,
    resident_state    varchar(2)   NOT NULL,
    university_id     bigint       NOT NULL REFERENCES university (id),
    grade             varchar(20)  NOT NULL,
    major             varchar(255) NOT NULL,
    -- One directory row per person: StudentRepository.findByEmail uses
    -- queryForObject, which throws on a second match.
    email             varchar(255) NOT NULL UNIQUE,
    social_media_link varchar(255)
);

CREATE INDEX idx_student_university ON student (university_id);

CREATE TABLE app_user (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role     varchar(20)  NOT NULL,
    email    varchar(255) NOT NULL UNIQUE,
    -- Nullable since Clerk became the identity provider. Nothing reads it.
    password varchar(255)
);

